import http from 'k6/http';
import { check, sleep } from 'k6';
import { Counter, Rate, Trend } from 'k6/metrics';

/**
 * ============================================================================
 * PeakConnect Concurrency Load Test: Booking Endpoint Stress Test
 * ============================================================================
 * 
 * Objective:
 * Target the booking endpoints specifically (/api/activities/{id},
 * /api/bookings/request, and /api/bookings/confirm) under concurrent Virtual User
 * (VU) load to verify that the pessimistic write lock and database check constraint
 * (current_occupancy <= capacity) prevent double-booking / overselling.
 * 
 * Scenario:
 * - A test activity and slot are created with a deliberately small capacity (default: 5).
 * - Up to 20 concurrent VUs ramp up, each representing a distinct trekker.
 * - Each VU:
 *     1. Fetches activity/slot details (hits dynamic pricing and risk calculation path).
 *     2. Requests guide matching for the slot (/api/bookings/request).
 *     3. Attempts to confirm a booking on the slot (/api/bookings/confirm).
 *     4. Records outcomes:
 *        - HTTP 200: Successful booking (must not exceed slot capacity).
 *        - HTTP 409: Expected slot-full conflict when capacity is reached.
 *        - 5xx / other: Unexpected application or infrastructure failure.
 * 
 * Thresholds:
 * - 'successful_bookings': count <= slotCapacity (CRITICAL CORRECTNESS ASSERTION)
 * - 'http_req_duration': p(95) < 1000ms
 * - 'booking_confirm_duration': p(95) < 1000ms
 * - 'error_rate': rate < 1% (unexpected errors, excluding 409 conflicts)
 * - 'unexpected_errors': count == 0
 * ============================================================================
 */

// Load pre-seeded test configuration generated by ./seed-data.sh
let testConfig;
try {
  testConfig = JSON.parse(open('./test-config.json'));
} catch (e) {
  // Fallback default structure if test-config.json has not yet been seeded
  testConfig = {
    baseUrl: 'http://localhost:8080',
    activityId: '',
    slotId: '',
    slotCapacity: 5,
    guideId: 'd7509423-98ec-4530-b75f-607bb1f3c99b',
    users: [],
  };
}

// Configurable test parameters via environment variables
const baseUrl = __ENV.BASE_URL || testConfig.baseUrl || 'http://localhost:8080';
const targetVUs = parseInt(__ENV.TARGET_VUS || '20', 10);
const rampUp = __ENV.RAMP_UP || '20s';
const holdDuration = __ENV.HOLD_DURATION || '40s';
const rampDown = __ENV.RAMP_DOWN || '10s';
const slotCapacity = __ENV.SLOT_CAPACITY ? parseInt(__ENV.SLOT_CAPACITY, 10) : (testConfig.slotCapacity || 5);
const sleepInterval = parseFloat(__ENV.SLEEP_INTERVAL || '0.5');

// Custom metrics for concurrency safety and performance
export const successfulBookings = new Counter('successful_bookings');
export const slotFullBookings = new Counter('slot_full_bookings');
export const unexpectedErrors = new Counter('unexpected_errors');
export const errorRate = new Rate('error_rate');

export const slotViewDuration = new Trend('slot_view_duration', true);
export const bookingRequestDuration = new Trend('booking_request_duration', true);
export const bookingConfirmDuration = new Trend('booking_confirm_duration', true);

// Test execution options
export const options = {
  stages: [
    { duration: rampUp, target: targetVUs },         // Stage 1: Ramp up to target VUs
    { duration: holdDuration, target: targetVUs },   // Stage 2: Sustained peak load
    { duration: rampDown, target: 0 },              // Stage 3: Graceful ramp down
  ],
  thresholds: {
    // Correctness Assertion: Under no circumstances should successful bookings exceed slot capacity!
    'successful_bookings': [`count<=${slotCapacity}`],
    // Latency SLAs: p95 duration must stay under 1000ms
    'http_req_duration': ['p(95)<1000'],
    'booking_confirm_duration': ['p(95)<1000'],
    // Error rate: unexpected errors must stay below 1%
    'error_rate': ['rate<0.01'],
    'unexpected_errors': ['count==0'],
  },
};

/**
 * Setup lifecycle: Verify configuration and initial state before VUs start.
 */
export function setup() {
  console.log('--- PeakConnect Concurrency Load Test Starting ---');
  console.log(`Base URL:      ${baseUrl}`);
  console.log(`Activity ID:   ${testConfig.activityId}`);
  console.log(`Slot ID:       ${testConfig.slotId}`);
  console.log(`Slot Capacity: ${slotCapacity}`);
  console.log(`Target VUs:    ${targetVUs}`);
  console.log(`Stages:        Ramp-up=${rampUp}, Hold=${holdDuration}, Ramp-down=${rampDown}`);
  console.log(`Seeded Users:  ${testConfig.users ? testConfig.users.length : 0}`);

  if (!testConfig.slotId || !testConfig.activityId) {
    throw new Error('Missing activityId or slotId in test-config.json. Run ./load-test/seed-data.sh first!');
  }

  return {
    startTime: new Date().toISOString(),
    slotCapacity: slotCapacity,
  };
}

/**
 * Main VU iteration function:
 * Simulates real user behavior hitting the booking funnel concurrently.
 */
export default function (data) {
  // Map virtual user to a pre-seeded trekker account
  const users = testConfig.users || [];
  const userIndex = (__VU - 1) % (users.length || 1);
  const user = users.length > 0 ? users[userIndex] : null;

  let token = user ? user.token : null;

  // If dynamic login is required
  if (!token && user && user.email) {
    const loginRes = http.post(
      `${baseUrl}/api/auth/login`,
      JSON.stringify({ email: user.email, password: 'password123' }),
      { headers: { 'Content-Type': 'application/json' } }
    );
    if (loginRes.status === 200) {
      token = JSON.parse(loginRes.body).token;
    }
  }

  const authHeaders = {
    'Content-Type': 'application/json',
    'Authorization': `Bearer ${token}`,
  };

  // --------------------------------------------------------------------------
  // STEP 1: View Activity & Slot (hits cached dynamic price and risk calculation)
  // --------------------------------------------------------------------------
  const viewRes = http.get(`${baseUrl}/api/activities/${testConfig.activityId}`, {
    headers: authHeaders,
    tags: { name: 'GET /api/activities/{id}' },
  });

  slotViewDuration.add(viewRes.timings.duration);
  const viewOk = check(viewRes, {
    'view activity status 200': (r) => r.status === 200,
  });

  if (!viewOk) {
    unexpectedErrors.add(1);
    errorRate.add(1);
    sleep(sleepInterval);
    return;
  }

  // --------------------------------------------------------------------------
  // STEP 2: Request Guide Matching (/api/bookings/request)
  // --------------------------------------------------------------------------
  const matchPayload = JSON.stringify({
    slotId: testConfig.slotId,
  });

  const matchRes = http.post(`${baseUrl}/api/bookings/request`, matchPayload, {
    headers: authHeaders,
    tags: { name: 'POST /api/bookings/request' },
  });

  bookingRequestDuration.add(matchRes.timings.duration);
  const matchOk = check(matchRes, {
    'guide match status 200': (r) => r.status === 200,
  });

  if (!matchOk) {
    unexpectedErrors.add(1);
    errorRate.add(1);
    sleep(sleepInterval);
    return;
  }

  // Determine guideId from response or fallback to testConfig
  let selectedGuideId = testConfig.guideId;
  try {
    const guides = JSON.parse(matchRes.body);
    if (Array.isArray(guides) && guides.length > 0 && guides[0].guideId) {
      selectedGuideId = guides[0].guideId;
    }
  } catch (e) {
    // keep default
  }

  // --------------------------------------------------------------------------
  // STEP 3: Confirm Booking (/api/bookings/confirm)
  // Concurrency-critical: uses pessimistic write lock on Slot
  // --------------------------------------------------------------------------
  const confirmPayload = JSON.stringify({
    slotId: testConfig.slotId,
    guideId: selectedGuideId,
  });

  const confirmRes = http.post(`${baseUrl}/api/bookings/confirm`, confirmPayload, {
    headers: authHeaders,
    tags: { name: 'POST /api/bookings/confirm' },
  });

  bookingConfirmDuration.add(confirmRes.timings.duration);

  if (confirmRes.status === 200) {
    // Booking successfully created within capacity
    successfulBookings.add(1);
    errorRate.add(0);
    check(confirmRes, {
      'booking confirmed (200)': (r) => r.status === 200,
    });
  } else if (confirmRes.status === 409) {
    // Slot is already full - expected graceful conflict rejection
    slotFullBookings.add(1);
    errorRate.add(0);
    check(confirmRes, {
      'slot full conflict handled (409)': (r) => r.status === 409,
    });
  } else {
    // Unexpected HTTP error (e.g., 500 Internal Server Error, 502, 401, etc.)
    unexpectedErrors.add(1);
    errorRate.add(1);
    console.error(`Unexpected booking response [status ${confirmRes.status}]: ${confirmRes.body}`);
    check(confirmRes, {
      'unexpected status error': (r) => false,
    });
  }

  // User pacing / think time before next attempt
  sleep(sleepInterval);
}

/**
 * Teardown lifecycle: Verify final database state and print summary.
 */
export function teardown(data) {
  console.log('\n--- PeakConnect Concurrency Load Test Finished ---');
  console.log(`Checking final slot occupancy via API...`);

  // Use admin token if available, or first trekker token
  const token = testConfig.adminToken || (testConfig.users && testConfig.users[0] ? testConfig.users[0].token : '');
  const res = http.get(`${baseUrl}/api/activities/${testConfig.activityId}`, {
    headers: {
      'Authorization': `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
  });

  if (res.status === 200) {
    try {
      const activity = JSON.parse(res.body);
      const slot = (activity.slots || []).find((s) => s.id === testConfig.slotId);
      if (slot) {
        console.log(`\n======================================================`);
        console.log(`FINAL SLOT STATE:`);
        console.log(`Slot ID:          ${slot.id}`);
        console.log(`Capacity:         ${slot.capacity}`);
        console.log(`CurrentOccupancy: ${slot.currentOccupancy}`);
        console.log(`======================================================`);

        if (slot.currentOccupancy <= slot.capacity) {
          console.log(`SUCCESS: Slot occupancy (${slot.currentOccupancy}) did not exceed capacity (${slot.capacity})!`);
        } else {
          console.error(`FAILURE: OVERSOLD! Slot occupancy (${slot.currentOccupancy}) exceeded capacity (${slot.capacity})!`);
        }
      }
    } catch (e) {
      console.warn('Could not parse activity response in teardown:', e);
    }
  } else {
    console.warn(`Could not fetch activity in teardown (status ${res.status})`);
  }
}
